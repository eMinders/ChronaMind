"""Evidence-status audit of every RL-* task (E-001).

Reads the task ids and claimed statuses from ``PLAN/TASK_GRAPH.md`` and the evidence each task is
backed by from ``PLAN/V2/status_evidence.json``, runs the named tests, and classifies every task:

* ``code-verified``     named files exist AND at least one named test passed, with none failed or skipped;
* ``doc-only``          a decision/specification record exists, with nothing executable to test;
* ``claimed-unverified`` something is claimed done/implemented but files are missing, or its tests
                         were skipped, absent, failed or not run;
* ``no-test``           a ``code`` task whose files exist, but whose ``tests`` list is empty or whose
                         test path/symbol does not resolve;
* ``not-started``       nothing exists and nothing is claimed (evidence cell reads ``UNVERIFIED``).

The audit document ``PLAN/V2/STATUS_AUDIT.md`` is generated by this script and never hand-edited.

Cited paths. For evidence-bearing kinds (``code``, ``doc``, ``config``) every cited file **and** test
path/symbol (supporting both ``tests/foo.py`` and ``tests/foo.py::test_bar``) is evidence and must exist:
a missing file or unresolved test symbol is a registry error and the script exits 1, in ``--check`` mode
too. For ``none`` (``not-started``) entries, ``files`` lists the *expected* deliverables, which are allowed
not to exist yet; that is what makes the task not-started.

The report records its generation environment (database, FalkorDB, prepared model assets, benchmark
corpora), UTC generation timestamp, and git revision when executed with ``--junit`` or a live test run.
If pytest crashes (``returncode >= 2`` or missing/malformed JUnit XML), the script exits non-zero without
overwriting ``PLAN/V2/STATUS_AUDIT.md``.

Staleness. The document ends with a machine-readable record (an HTML comment) of what its run measured: the
revision, timestamp, environment, and the junit counts of every node a cited test matched. ``--check`` re-renders
the document from that record and the *current* ``TASK_GRAPH.md``, registry, repository files and renderer, and
fails if the result differs from the committed text in any byte. So a stale document (an edited registry, a moved
file, a renamed test, a renderer change) fails CI deterministically, without a database. What ``--check`` cannot
see is a test whose *result* changed since the recorded run: that needs a test run, and the recorded revision and
timestamp say how old the measured results are.

Run:   uv run python scripts/audit_status.py            # run tests, write STATUS_AUDIT.md
       uv run python scripts/audit_status.py --check    # registry checks + re-render comparison, CI-safe
       uv run python scripts/audit_status.py --junit F  # reuse an existing pytest junit XML
Exit:  0 when every task is classified and the document is current; 1 when any task is unclassified, the registry
       is stale, the committed document differs from what the renderer produces, or pytest crashes.
"""

