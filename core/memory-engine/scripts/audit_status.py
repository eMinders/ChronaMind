def _has_direction_notice(relative: str) -> bool:
    head = (ROOT / relative).read_text(encoding="utf-8")[:2500]
    return "Direction notice" in head and "V2/" in head


def reconciliation(results: list[Result]) -> list[str]:
    """Measured resolution of every drift item in TRANSITION_AUDIT.md section 2."""

    def tally(rows: list[Result]) -> str:
        counts = Counter(r.classification for r in rows)
        return ", ".join(f"{counts[c]} {c}" for c in CLASSES if counts[c]) or "none"

    p0 = _span(results, "RL-001", "RL-006")
    engine = _span(results, "RL-040", "RL-061")
    lines = [
        "## Reconciliation with the transition audit",
        "",
        "Each row of `PLAN/V2/TRANSITION_AUDIT.md` section 2 (planning-document drift), checked against the",
        "repository by this script.",
        "",
        "| Document | Claim | Measured | Resolution |",
        "|---|---|---|---|",
    ]
    for doc, claim, relative, task in DRIFT_NOTICE_DOCS:
        noted = _has_direction_notice(relative)
        verdict = "direction notice present" if noted else "**OPEN: no direction notice**"
        lines.append(f"| {doc} | {claim} | {verdict} | closed by `{task}`; nothing rewritten |")
    lines.append(
        f"| `PLAN/PROJECT_STATUS.md` section 1 | engine `P4`-`P7` not executed | `RL-040`-`RL-061`: {tally(engine)}"
        " | stale claim; code and tests exist |"
    )
    lines.append(
        f"| `PLAN/TASK_GRAPH.md` | Phase P0 `Complete` | `RL-001`-`RL-006`: {tally(p0)}"
        " | supported except rows listed under discrepancies; retained as the v1 record |"
    )
    workflow_claim = ROOT.parent / ".github" / "workflows" / "research-lab.yaml"
    workflow_real = ROOT.parent.parent / ".github" / "workflows" / "custom-memory-engine.yaml"
    lines.append(
        "| Issue #12 title | `.github/workflows/research-lab.yaml` | "
        f"claimed file {'exists' if workflow_claim.exists() else 'missing'}; "
        f"`custom-memory-engine.yaml` {'exists' if workflow_real.exists() else 'missing'}"
        " | the evidence registry cites the real file (`RL-005`) |"
    )
    refactoring = (ROOT / "REFACTORING.md").read_text(encoding="utf-8")
    stale = "peer review on `#45`" in refactoring
    lines.append(
        "| `REFACTORING.md` section 6 | remaining work: peer review on `#45` | "
        f"sentence {'still present' if stale else 'absent'}; `RL-061` is "
        f"{next(r.classification for r in results if r.task == 'RL-061')} | "
        "historical sentence kept (additive-only policy); no action |"
    )
    return lines


def _tcp_open(host: str, port: int) -> bool:
    try:
        with socket.create_connection((host, port), timeout=2):
            return True
    except OSError:
        return False


def environment(env: dict[str, str] | None = None, root: Path = ROOT) -> list[tuple[str, str]]:
    """What this run could measure. Deterministic for a given environment (no timestamps)."""
    env = dict(os.environ) if env is None else env
    rows: list[tuple[str, str]] = []
    url = env.get("CME_TEST_DATABASE_URL", "")
    if url:
        parts = urlsplit(url)
        reachable = _tcp_open(parts.hostname or "localhost", parts.port or 5432)
        state = "set, reachable" if reachable else "set, **not reachable**"
        rows.append(("Database (`CME_TEST_DATABASE_URL`)", state))
    else:
        rows.append(("Database (`CME_TEST_DATABASE_URL`)", "**not set**: DB-backed tests skip"))
    port = env.get("CME_BASELINE_TEST_FALKOR_PORT", "")
    if port.isdigit():
        rows.append(("FalkorDB", "reachable" if _tcp_open("localhost", int(port)) else "**not reachable**"))
    else:
        rows.append(("FalkorDB", "**not configured**"))
    assets = env.get("CME_BASELINE_TEST_ASSETS", "")
    present = bool(assets) and Path(assets).is_dir() and any(Path(assets).iterdir())
    rows.append(("Prepared model assets (`CME_BASELINE_TEST_ASSETS`)", "present" if present else "**absent**"))
    for corpus in ("longmemeval", "locomo"):
        data = root / "research" / "benchmarks" / corpus / "data"
        here = data.is_dir() and any(data.iterdir())
        rows.append((f"Benchmark corpus `{corpus}`", "present" if here else "**absent** (gitignored download)"))
    return rows


def _git_sha() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=False
    )
    return result.stdout.strip() or "unknown"


def _cell(result: Result) -> str:
    if result.classification == "not-started":
        return "UNVERIFIED (nothing exists)"
    files = ", ".join(f"`{f}`" for f in result.files[:3])
    more = f" (+{len(result.files) - 3} more)" if len(result.files) > 3 else ""
    if result.tests:
        tests = ", ".join(f"`{t}`" for t in result.tests[:2])
        more_t = f" (+{len(result.tests) - 2})" if len(result.tests) > 2 else ""
        return f"{files}{more}; tests: {tests}{more_t}"
    return f"{files}{more}; tests: UNVERIFIED (no executable test)"


def render(
    results: list[Result],
    ran_tests: bool,
    env_rows: list[tuple[str, str]] | None = None,
    *,
    timestamp: str | None = None,
    revision: str | None = None,
    junit_record: dict[str, Outcome] | None = None,
) -> str:
    """Render the generated audit document; with ``junit_record``, end it with the record ``--check`` re-renders."""
    counts = Counter(r.classification for r in results)
    rev = revision if revision is not None else _git_sha()
    env = env_rows if env_rows is not None else environment()
    header = [
        "# Status Audit (generated)",
        "",
        "> **Generated by `scripts/audit_status.py` from `PLAN/TASK_GRAPH.md` and `PLAN/V2/status_evidence.json`.**",
        "> Do not edit by hand; re-run the script. Task `E-001`.",
        "",
        f"- Source commit: `{rev}`",
    ]
    if timestamp is not None:
        header.append(f"- Generated at (UTC): `{timestamp}`")
    header += [
        f"- Tests executed for this audit: {'yes' if ran_tests else 'no (registry check only)'}",
        "- A task is `code-verified` only if its named files exist **and** at least one named test passed.",
        "  Tests that need the disposable database are skipped without one, which downgrades those",
        "  tasks to `claimed-unverified` rather than passing them silently.",
        "",
        "## Generation environment",
        "",
        "State when this report was rendered, i.e. after the test run (benchmark tests fetch missing corpora",
        "themselves, checksum-verified).",
        "",
        "| Item | State |",
        "|---|---|",
        *[f"| {item} | {state} |" for item, state in env],
        "",
        "## Summary",
        "",
        "| Classification | Tasks |",
        "|---|---:|",
        *[f"| `{c}` | {counts.get(c, 0)} |" for c in CLASSES],
        f"| **Total** | **{len(results)}** |",
        "",
        "## Discrepancies between claimed status and evidence",
        "",
    ]
    lines = list(header)
    found = discrepancies(results)
    lines += [f"- {d}" for d in found] or ["None."]
    lines += ["", *reconciliation(results)]
    lines += [
        "",
        "## All tasks",
        "",
        "| Task | Claimed (TASK_GRAPH) | Audit | Evidence (file; test) | Notes |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        notes = "; ".join([*r.reasons, r.note] if r.note else r.reasons)
        lines.append(f"| `{r.task}` | {r.claim.strip('` ')} | `{r.classification}` | {_cell(r)} | {notes} |")
    if junit_record is not None:
        record = {
            "revision": rev,
            "timestamp": timestamp,
            "ran_tests": ran_tests,
            "environment": [list(row) for row in env],
            "junit": {k: [o.passed, o.failed, o.skipped] for k, o in sorted(junit_record.items())},
        }
        lines += ["", RECORD_PREFIX + json.dumps(record, sort_keys=True, separators=(",", ":")) + RECORD_SUFFIX]
    lines.append("")
    return "\n".join(lines)


def check_document(text: str, claims: dict[str, str], registry: dict[str, dict], root: Path = ROOT) -> list[str]:
    """Re-render ``text`` from its own record and the current inputs; return why it is stale (empty when current)."""
    records = [line for line in text.splitlines() if line.startswith(RECORD_PREFIX) and line.endswith(RECORD_SUFFIX)]
    if len(records) != 1:
        return ["status_audit_record_missing: regenerate with scripts/audit_status.py"]
    try:
        record = json.loads(records[0][len(RECORD_PREFIX) : -len(RECORD_SUFFIX)])
        junit = {k: Outcome(int(v[0]), int(v[1]), int(v[2]), ran=True) for k, v in record["junit"].items()}
        env_rows = [(str(item), str(state)) for item, state in record["environment"]]
        expected = render(
            audit(claims, registry, junit, root, ran=bool(record["ran_tests"])),
            bool(record["ran_tests"]),
            env_rows,
            timestamp=record["timestamp"],
            revision=str(record["revision"]),
            junit_record=junit,
        )
    except (ValueError, KeyError, TypeError, IndexError):
        return ["status_audit_record_malformed: regenerate with scripts/audit_status.py"]
    if expected == text:
        return []
    committed, rendered = text.splitlines(), expected.splitlines()
    line = next(
        (n for n, (a, b) in enumerate(zip(committed, rendered, strict=False), start=1) if a != b),
        min(len(committed), len(rendered)) + 1,
    )
    return [f"status_audit_stale: line {line} differs from what scripts/audit_status.py renders; regenerate it"]


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--check", action="store_true", help="verify the registry and that --out is what the renderer produces"
    )
    parser.add_argument("--junit", type=Path, help="reuse an existing pytest junit XML instead of running tests")
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument("--timestamp", default=None, help="override UTC generation timestamp (ISO-8601)")
    args = parser.parse_args(argv)

    claims = parse_task_graph(TASK_GRAPH.read_text(encoding="utf-8"))
    registry = load_registry(REGISTRY)
    problems = check_registry(claims, registry)
    for problem in problems:
        print(problem)
    if problems:
        print(f"audit_status: {len(problems)} problem(s); tasks must be classified and cited evidence must exist")
        return 1
    if args.check:
        if args.out.is_file():
            stale = check_document(args.out.read_text(encoding="utf-8"), claims, registry)
        else:
            stale = [f"status_audit_missing: {args.out.name}"]
        for problem in stale:
            print(problem)
        if stale:
            return 1
        print(f"audit_status: {len(claims)} tasks, all present in the evidence registry; {args.out.name} is current")
        return 0

    junit: dict[str, Outcome] = {}
    try:
        if args.junit:
            junit = read_junit(args.junit)
        else:
            tests = sorted({t for entry in registry.values() for t in entry.get("tests", [])})
            with tempfile.TemporaryDirectory() as tmp:
                junit_path = Path(tmp) / "junit.xml"
                run_pytest(tests, junit_path)
                junit = read_junit(junit_path)
    except (PytestCrashError, ET.ParseError, ValueError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 1

    timestamp = args.timestamp or datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    revision = _git_sha()
    results = audit(claims, registry, junit)
    args.out.write_text(
        render(
            results,
            bool(junit),
            environment(),
            timestamp=timestamp,
            revision=revision,
            junit_record=cited_junit(registry, junit),
        ),
        encoding="utf-8",
        newline="\n",
    )
    counts = Counter(r.classification for r in results)
    print("audit_status:", ", ".join(f"{c}={counts.get(c, 0)}" for c in CLASSES), f"-> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
