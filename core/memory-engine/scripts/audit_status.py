ROOT = Path(__file__).resolve().parents[1]
TASK_GRAPH = ROOT / "PLAN" / "TASK_GRAPH.md"
REGISTRY = ROOT / "PLAN" / "V2" / "status_evidence.json"
OUTPUT = ROOT / "PLAN" / "V2" / "STATUS_AUDIT.md"

TASK_ROW = re.compile(r"^\| `(RL-\d{3})` \|.*$", re.M)
RECORD_PREFIX = "<!-- audit-record: "
RECORD_SUFFIX = " -->"
KINDS = ("code", "doc", "config", "none")
CLASSES = ("code-verified", "doc-only", "claimed-unverified", "no-test", "not-started")


class PytestCrashError(RuntimeError):
    """Raised when pytest aborts or fails to emit valid JUnit XML."""


@dataclass(frozen=True)
class Outcome:
    """Aggregated pytest results for one task's named tests."""

    passed: int = 0
    failed: int = 0
    skipped: int = 0
    missing: tuple[str, ...] = ()
    ran: bool = False


@dataclass(frozen=True)
class Result:
    """Audit verdict for one task."""

    task: str
    claim: str
    kind: str
    classification: str
    files: tuple[str, ...]
    files_missing: tuple[str, ...]
    tests: tuple[str, ...]
    outcome: Outcome
    note: str = ""
    reasons: tuple[str, ...] = field(default_factory=tuple)


def claim_group(claim: str) -> str:
    """Bucket a TASK_GRAPH status cell: ``done``, ``partial`` or ``open``."""
    text = claim.strip("` ").lower()
    if text.startswith(("complete", "done")):
        return "done"
    if text.startswith(("implemented", "partial")):
        return "partial"
    return "open"


def classify(
    kind: str,
    claim: str,
    files_missing: tuple[str, ...],
    files_total: int,
    outcome: Outcome,
    *,
    tests_valid: bool = True,
) -> str:
    """Pure classification rule; see the module docstring."""
    if kind not in KINDS:
        raise ValueError(f"unknown_kind:{kind}")
    claimed = claim_group(claim) in ("done", "partial")
    if kind == "none":
        return "claimed-unverified" if files_total > len(files_missing) else "not-started"
    if files_missing:
        return "claimed-unverified" if claimed else "not-started"
    if kind == "doc":
        return "doc-only"
    if kind == "config":
        return "claimed-unverified"
    if not tests_valid:
        return "no-test"
    clean = outcome.passed > 0 and outcome.failed == 0 and outcome.skipped == 0 and not outcome.missing
    return "code-verified" if clean else "claimed-unverified"


def parse_task_graph(text: str) -> dict[str, str]:
    """Return ``{task_id: status_cell}`` for every table row in TASK_GRAPH."""
    claims: dict[str, str] = {}
    for line in text.splitlines():
        match = TASK_ROW.match(line)
        if not match:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        claims[match.group(1)] = cells[4] if len(cells) > 4 else ""
    return claims


def load_registry(path: Path) -> dict[str, dict]:
    """Load the evidence registry."""
    return json.loads(path.read_text(encoding="utf-8"))["tasks"]


def _split_citation(citation: str) -> tuple[str, str]:
    path, _, symbol = citation.partition("::")
    return path, symbol


def _defined_test_symbols(path: Path) -> set[str]:
    """Extract test function, async test function, and ``Class::method`` names via AST."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError, OSError):
        return set()
    names = {
        node.name
        for node in ast.walk(tree)
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.name.startswith("test")
    }
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            names.add(node.name)
            for member in node.body:
                if isinstance(member, ast.FunctionDef | ast.AsyncFunctionDef) and member.name.startswith("test"):
                    names.add(f"{node.name}::{member.name}")
    return names


def resolve_test_citation(citation: str, root: Path = ROOT) -> bool:
    """Return True when ``citation`` (``file.py`` or ``file.py::symbol``) resolves to an existing test."""
    path_str, symbol = _split_citation(citation)
    if not path_str:
        return False
    target = (root / path_str).resolve()
    if not target.is_file():
        return False
    if not symbol:
        return True
    if target.suffix != ".py":
        return False
    base_symbol = symbol.split("[", 1)[0]
    return base_symbol in _defined_test_symbols(target)


def check_registry(claims: dict[str, str], registry: dict[str, dict], root: Path = ROOT) -> list[str]:
    """Return problems that make the audit incomplete: unclassified/stale tasks or missing evidence paths/symbols."""
    problems = [f"unclassified_task:{t}" for t in sorted(set(claims) - set(registry))]
    problems += [f"registry_entry_without_task:{t}" for t in sorted(set(registry) - set(claims))]
    problems += [
        f"unknown_kind:{t}:{e.get('kind')}" for t, e in sorted(registry.items()) if e.get("kind") not in KINDS
    ]
    problems += missing_evidence(registry, root)
    return problems


def missing_evidence(registry: dict[str, dict], root: Path = ROOT) -> list[str]:
    """Cited evidence paths/symbols that do not exist (``none`` entries cite expected deliverables and are exempt)."""
    problems: list[str] = []
    for task, entry in sorted(registry.items()):
        if entry.get("kind") == "none":
            continue
        for path in entry.get("files", []):
            if not (root / path).resolve().exists():
                problems.append(f"missing_evidence_path:{task}:{path}")
        for test in entry.get("tests", []):
            path_str, symbol = _split_citation(test)
            target = (root / path_str).resolve()
            if not target.is_file():
                problems.append(f"missing_evidence_path:{task}:{test}")
            elif symbol and not resolve_test_citation(test, root):
                problems.append(f"missing_evidence_symbol:{task}:{test}")
    return problems


def _node_key(test_path: str) -> str:
    return test_path.removesuffix(".py").replace("/", ".")


def read_junit(path: Path) -> dict[str, Outcome]:
    """Aggregate a pytest junit XML into Outcome entries per dotted module and ``module::test`` node."""
    root = ET.parse(path).getroot()
    if root.tag not in ("testsuites", "testsuite"):
        raise ValueError(f"invalid_junit_root:{root.tag}")
    counts: dict[str, list[int]] = {}
    for case in root.iter("testcase"):
        module = case.get("classname", "")
        name = case.get("name", "")
        bucket_idx = (
            1
            if (case.find("failure") is not None or case.find("error") is not None)
            else (2 if case.find("skipped") is not None else 0)
        )
        counts.setdefault(module, [0, 0, 0])[bucket_idx] += 1
        if name:
            base_name = name.split("[", 1)[0]
            counts.setdefault(f"{module}::{base_name}", [0, 0, 0])[bucket_idx] += 1
            if base_name != name:
                counts.setdefault(f"{module}::{name}", [0, 0, 0])[bucket_idx] += 1
    return {m: Outcome(c[0], c[1], c[2], ran=True) for m, c in counts.items()}


def _matching_keys(test: str, junit: dict[str, Outcome]) -> list[str]:
    """The junit keys whose counts ``test`` (``file.py``, ``file.py::name`` or ``file.py::Class::name``) sums."""
    path_str, symbol = _split_citation(test)
    mod_key = _node_key(path_str)
    module_keys = [k for k in junit if "::" not in k]
    node_keys = [k for k in junit if "::" in k]
    if not symbol:
        return [module for module in module_keys if module == mod_key or module.startswith(mod_key + ".")]
    if "::" in symbol:
        cls_name, _, func_name = symbol.partition("::")
        exact_mod = f"{mod_key}.{cls_name}"
        return [k for k in node_keys if k == f"{exact_mod}::{func_name}"]
    matched = [
        k
        for k in node_keys
        if (m := k.partition("::")[0])
        and (m == mod_key or m.startswith(mod_key + "."))
        and k.partition("::")[2] == symbol
    ]
    if not matched and "[" not in symbol:
        matched = [module for module in module_keys if module == f"{mod_key}.{symbol}"]
    return matched


def _match_node(test: str, junit: dict[str, Outcome]) -> list[Outcome]:
    return [junit[k] for k in _matching_keys(test, junit)]


def cited_junit(registry: dict[str, dict], junit: dict[str, Outcome]) -> dict[str, Outcome]:
    """The part of ``junit`` any cited test matches: auditing with it gives the same verdicts as the whole run."""
    keys = {k for entry in registry.values() for test in entry.get("tests", []) for k in _matching_keys(test, junit)}
    return {k: junit[k] for k in sorted(keys)}


def outcome_for(tests: tuple[str, ...], junit: dict[str, Outcome], *, ran: bool | None = None) -> Outcome:
    """Sum the junit results of the modules or test nodes named by ``tests``; ``ran`` defaults to ``bool(junit)``."""
    passed = failed = skipped = 0
    missing: list[str] = []
    for test in tests:
        matched = _match_node(test, junit)
        if not matched:
            missing.append(test)
            continue
        passed += sum(o.passed for o in matched)
        failed += sum(o.failed for o in matched)
        skipped += sum(o.skipped for o in matched)
    return Outcome(passed, failed, skipped, tuple(missing), ran=bool(junit) if ran is None else ran)


def run_pytest(tests: list[str], junit_path: Path) -> None:
    """Run the named tests once; raise :class:`PytestCrashError` if pytest aborts or fails to emit XML."""
    args = ["-q", "-p", "no:cacheprovider", f"--junitxml={junit_path}", *tests]
    # psycopg's async mode cannot use the Windows default Proactor loop; select the Selector loop there.
    launcher = (
        "import asyncio, sys, pytest;"
        "sys.platform == 'win32' and asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy());"
        "sys.exit(pytest.main(sys.argv[1:]))"
    )
    proc = subprocess.run(
        [sys.executable, "-c", launcher, *args],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    if proc.returncode >= 2 or proc.returncode < 0:
        detail = (proc.stderr or proc.stdout or "").strip()
        raise PytestCrashError(
            f"audit_status: pytest crashed (exit {proc.returncode}); refusing to overwrite {OUTPUT.name}"
            + (f"\n{detail}" if detail else "")
        )
    if not junit_path.is_file():
        raise PytestCrashError(
            f"audit_status: pytest did not produce {junit_path}; refusing to overwrite {OUTPUT.name}"
        )


def audit(
    claims: dict[str, str],
    registry: dict[str, dict],
    junit: dict[str, Outcome],
    root: Path = ROOT,
    *,
    ran: bool | None = None,
) -> list[Result]:
    """Classify every task; ``ran`` (whether tests were run) defaults to ``bool(junit)``."""
    ran = bool(junit) if ran is None else ran
    results: list[Result] = []
    for task in sorted(claims):
        entry = registry[task]
        files = tuple(entry.get("files", []))
        tests = tuple(entry.get("tests", []))
        missing = tuple(f for f in files if not (root / f).resolve().exists())
        tests_unresolved = tuple(t for t in tests if not resolve_test_citation(t, root))
        tests_valid = entry["kind"] != "code" or (bool(tests) and not tests_unresolved)
        outcome = outcome_for(tests, junit, ran=ran) if (tests and not tests_unresolved) else Outcome(ran=ran)
        classification = classify(
            entry["kind"],
            claims[task],
            missing,
            len(files),
            outcome,
            tests_valid=tests_valid,
        )
        reasons: list[str] = []
        if missing:
            reasons.append("missing: " + ", ".join(missing))
        if entry["kind"] == "code" and not tests:
            reasons.append("no tests cited")
        elif tests_unresolved:
            reasons.append("unresolved tests: " + ", ".join(tests_unresolved))
        elif tests and not outcome.ran:
            reasons.append("tests not run")
        elif tests and outcome.missing:
            reasons.append("not collected: " + ", ".join(outcome.missing))
        if tests and not tests_unresolved and outcome.ran and outcome.passed == 0 and not outcome.missing:
            reasons.append(f"no passing test (skipped {outcome.skipped}, failed {outcome.failed})")
        elif outcome.skipped:
            reasons.append(f"{outcome.skipped} skipped (environment-gated)")
        if outcome.failed:
            reasons.append(f"{outcome.failed} failing")
        results.append(
            Result(
                task,
                claims[task],
                entry["kind"],
                classification,
                files,
                missing,
                tests,
                outcome,
                entry.get("note", ""),
                tuple(reasons),
            )
        )
    return results


def discrepancies(results: list[Result]) -> list[str]:
    """Where the TASK_GRAPH claim and the measured evidence disagree."""
    found: list[str] = []
    for r in results:
        group = claim_group(r.claim)
        if group == "done" and r.classification not in ("code-verified", "doc-only"):
            why = "; ".join(r.reasons) or "no executable evidence"
            found.append(f"{r.task}: claimed `{r.claim.strip('` ')}` but audit says {r.classification} ({why})")
        if group == "open" and r.classification in ("code-verified", "doc-only"):
            found.append(f"{r.task}: claimed `{r.claim.strip('` ')}` but evidence exists ({r.classification})")
    return found


def _span(results: list[Result], first: str, last: str) -> list[Result]:
    return [r for r in results if first <= r.task <= last]


