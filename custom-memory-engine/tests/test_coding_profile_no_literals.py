"""Check that the coding profile's identity is absent from source assets.

The profile document itself and generated bytecode are excluded. This catches
quoted occurrences in any source file and Python literals decoded by ``ast``;
dynamic construction or opaque binary representations are outside its scope.
"""

import ast
import re
from pathlib import Path

_QUOTED_NAME = re.compile(rb"(['\"])coding\1")


def _profile_name_literals(root: Path) -> list[tuple[Path, int]]:
    """Return each source file and line containing the prohibited literal."""
    allowed = root / "custom_memory_engine" / "profiles" / "coding.json"
    findings: set[tuple[Path, int]] = set()
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path == allowed or "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        raw = path.read_bytes()
        findings.update((path, raw.count(b"\n", 0, match.start()) + 1) for match in _QUOTED_NAME.finditer(raw))
        if path.suffix == ".py":
            tree = ast.parse(raw.decode("utf-8-sig"), filename=str(path))
            findings.update(
                (path, node.lineno)
                for node in ast.walk(tree)
                if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value == "coding"
            )
    return sorted(findings)


def test_engine_source_contains_no_coding_profile_name_literal() -> None:
    root = Path(__file__).resolve().parents[1] / "src"
    assert not _profile_name_literals(root)


def test_literal_check_detects_a_python_profile_name_branch(tmp_path: Path) -> None:
    source = tmp_path / "violation.py"
    source.write_text('if profile.name == "coding":\n    pass\n', encoding="utf-8")
    assert _profile_name_literals(tmp_path) == [(source, 1)]


def test_literal_check_detects_non_python_source(tmp_path: Path) -> None:
    source = tmp_path / "policy.sql"
    source.write_text("SELECT 1;\nSELECT 'coding';\n", encoding="utf-8")
    assert _profile_name_literals(tmp_path) == [(source, 2)]


def test_literal_check_allows_profile_document_and_configuration(tmp_path: Path) -> None:
    allowed = tmp_path / "custom_memory_engine" / "profiles" / "coding.json"
    allowed.parent.mkdir(parents=True)
    allowed.write_text('{"name": "coding"}', encoding="utf-8")
    source = tmp_path / "allowed.py"
    source.write_text('if "claim" in profile.kinds:\n    label = "encoding"\n', encoding="utf-8")
    assert not _profile_name_literals(tmp_path)
