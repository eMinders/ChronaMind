"""Evidence-status audit of every RL-* task (E-001).

Reads the task ids and claimed statuses from ``PLAN/TASK_GRAPH.md`` and the evidence each task is
backed by from ``PLAN/V2/status_evidence.json``, runs the named tests, and classifies every task:

* ``code-verified``     named files exist AND at least one named test passed, with none failed or skipped;
* ``doc-only``          a decision/specification record exists, with nothing executable to test;
* ``claimed-unverified`` something is claimed done/implemented but files are missing, or its tests
                         were skipped, absent, failed or not run;
* ``not-started``       nothing exists and nothing is claimed (evidence cell reads ``UNVERIFIED``).

The audit document ``PLAN/V2/STATUS_AUDIT.md`` is generated by this script and never hand-edited.

Run:   uv run python scripts/audit_status.py            # run tests, write STATUS_AUDIT.md
       uv run python scripts/audit_status.py --check    # registry completeness only (no tests), CI-safe
       uv run python scripts/audit_status.py --junit F  # reuse an existing pytest junit XML
Exit:  0 when every task is classified, 1 when any task is unclassified or the registry is stale.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASK_GRAPH = ROOT / "PLAN" / "TASK_GRAPH.md"
REGISTRY = ROOT / "PLAN" / "V2" / "status_evidence.json"
OUTPUT = ROOT / "PLAN" / "V2" / "STATUS_AUDIT.md"

TASK_ROW = re.compile(r"^\| `(RL-\d{3})` \|.*$", re.M)
KINDS = ("code", "doc", "config", "none")
CLASSES = ("code-verified", "doc-only", "claimed-unverified", "not-started")


@dataclass(frozen=True)
class Outcome:
    """Aggregated pytest results for one task's named tests."""

    passed: int = 0
    failed: int = 0
    skipped: int = 0
    missing: tuple[str, ...] = ()
    ran: bool = False


@dataclass(frozen=True)
class Result:
    """Audit verdict for one task."""

    task: str
    claim: str
    kind: str
    classification: str
    files: tuple[str, ...]
    files_missing: tuple[str, ...]
    tests: tuple[str, ...]
    outcome: Outcome
    note: str = ""
    reasons: tuple[str, ...] = field(default_factory=tuple)


def claim_group(claim: str) -> str:
    """Bucket a TASK_GRAPH status cell: ``done``, ``partial`` or ``open``."""
    text = claim.strip("` ").lower()
    if text.startswith(("complete", "done")):
        return "done"
    if text.startswith(("implemented", "partial")):
        return "partial"
    return "open"


def classify(kind: str, claim: str, files_missing: tuple[str, ...], files_total: int, outcome: Outcome) -> str:
    """Pure classification rule; see the module docstring."""
    if kind not in KINDS:
        raise ValueError(f"unknown_kind:{kind}")
    claimed = claim_group(claim) in ("done", "partial")
    if kind == "none":
        return "claimed-unverified" if files_total > len(files_missing) else "not-started"
    if files_missing:
        return "claimed-unverified" if claimed else "not-started"
    if kind == "doc":
        return "doc-only"
    if kind == "config":
        return "claimed-unverified"
    clean = outcome.passed > 0 and outcome.failed == 0 and outcome.skipped == 0 and not outcome.missing
    return "code-verified" if clean else "claimed-unverified"


def parse_task_graph(text: str) -> dict[str, str]:
    """Return ``{task_id: status_cell}`` for every table row in TASK_GRAPH."""
    claims: dict[str, str] = {}
    for line in text.splitlines():
        match = TASK_ROW.match(line)
        if not match:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        claims[match.group(1)] = cells[4] if len(cells) > 4 else ""
    return claims


def load_registry(path: Path) -> dict[str, dict]:
    """Load the evidence registry."""
    return json.loads(path.read_text(encoding="utf-8"))["tasks"]


def check_registry(claims: dict[str, str], registry: dict[str, dict]) -> list[str]:
    """Return problems that make the audit incomplete (unclassified or stale tasks)."""
    problems = [f"unclassified_task:{t}" for t in sorted(set(claims) - set(registry))]
    problems += [f"registry_entry_without_task:{t}" for t in sorted(set(registry) - set(claims))]
    problems += [
        f"unknown_kind:{t}:{e.get('kind')}" for t, e in sorted(registry.items()) if e.get("kind") not in KINDS
    ]
    return problems


def _node_key(test_path: str) -> str:
    return test_path.removesuffix(".py").replace("/", ".")


def read_junit(path: Path) -> dict[str, Outcome]:
    """Aggregate a pytest junit XML into one Outcome per dotted test-module prefix."""
    counts: dict[str, list[int]] = {}
    for case in ET.parse(path).getroot().iter("testcase"):
        module = case.get("classname", "")
        bucket = counts.setdefault(module, [0, 0, 0])
        if case.find("failure") is not None or case.find("error") is not None:
            bucket[1] += 1
        elif case.find("skipped") is not None:
            bucket[2] += 1
        else:
            bucket[0] += 1
    return {m: Outcome(c[0], c[1], c[2], ran=True) for m, c in counts.items()}


def outcome_for(tests: tuple[str, ...], junit: dict[str, Outcome]) -> Outcome:
    """Sum the junit results of the modules named by ``tests``."""
    passed = failed = skipped = 0
    missing: list[str] = []
    for test in tests:
        key = _node_key(test)
        matched = [o for module, o in junit.items() if module == key or module.startswith(key + ".")]
        if not matched:
            missing.append(test)
            continue
        passed += sum(o.passed for o in matched)
        failed += sum(o.failed for o in matched)
        skipped += sum(o.skipped for o in matched)
    return Outcome(passed, failed, skipped, tuple(missing), ran=bool(junit))


def run_pytest(tests: list[str], junit_path: Path) -> None:
    """Run the named tests once; a non-zero pytest exit is expected when something fails or skips."""
    args = ["-q", "-p", "no:cacheprovider", f"--junitxml={junit_path}", *tests]
    # psycopg's async mode cannot use the Windows default Proactor loop; select the Selector loop there.
    launcher = (
        "import asyncio, sys, pytest;"
        "sys.platform == 'win32' and asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy());"
        "sys.exit(pytest.main(sys.argv[1:]))"
    )
    subprocess.run([sys.executable, "-c", launcher, *args], cwd=ROOT, check=False, capture_output=True)


def audit(claims: dict[str, str], registry: dict[str, dict], junit: dict[str, Outcome]) -> list[Result]:
    """Classify every task."""
    results: list[Result] = []
    for task in sorted(claims):
        entry = registry[task]
        files = tuple(entry.get("files", []))
        tests = tuple(entry.get("tests", []))
        missing = tuple(f for f in files if not (ROOT / f).resolve().exists())
        outcome = outcome_for(tests, junit) if tests else Outcome(ran=bool(junit))
        classification = classify(entry["kind"], claims[task], missing, len(files), outcome)
        reasons: list[str] = []
        if missing:
            reasons.append("missing: " + ", ".join(missing))
        if tests and not outcome.ran:
            reasons.append("tests not run")
        elif tests and outcome.missing:
            reasons.append("not collected: " + ", ".join(outcome.missing))
        if tests and outcome.ran and outcome.passed == 0 and not outcome.missing:
            reasons.append(f"no passing test (skipped {outcome.skipped}, failed {outcome.failed})")
        elif outcome.skipped:
            reasons.append(f"{outcome.skipped} skipped (environment-gated)")
        if outcome.failed:
            reasons.append(f"{outcome.failed} failing")
        results.append(
            Result(
                task,
                claims[task],
                entry["kind"],
                classification,
                files,
                missing,
                tests,
                outcome,
                entry.get("note", ""),
                tuple(reasons),
            )
        )
    return results


def discrepancies(results: list[Result]) -> list[str]:
    """Where the TASK_GRAPH claim and the measured evidence disagree."""
    found: list[str] = []
    for r in results:
        group = claim_group(r.claim)
        if group == "done" and r.classification not in ("code-verified", "doc-only"):
            why = "; ".join(r.reasons) or "no executable evidence"
            found.append(f"{r.task}: claimed `{r.claim.strip('` ')}` but audit says {r.classification} ({why})")
        if group == "open" and r.classification in ("code-verified", "doc-only"):
            found.append(f"{r.task}: claimed `{r.claim.strip('` ')}` but evidence exists ({r.classification})")
    return found


def _span(results: list[Result], first: str, last: str) -> list[Result]:
    return [r for r in results if first <= r.task <= last]


DRIFT_NOTICE_DOCS = (
    ("`PLAN/PROJECT_STATUS.md` section 1", 'Engine work "Not Yet Executed"', "PLAN/PROJECT_STATUS.md", "E-003"),
    ("`PROJECT_ROADMAP.md` section A", '`P0` "READY TO START"', "PROJECT_ROADMAP.md", "E-003"),
    ("`PLAN/SCHEDULE.md`", "24-week `P0`-`P13` calendar", "PLAN/SCHEDULE.md", "E-003"),
)


def _has_direction_notice(relative: str) -> bool:
    head = (ROOT / relative).read_text(encoding="utf-8")[:2500]
    return "Direction notice" in head and "V2/" in head


def reconciliation(results: list[Result]) -> list[str]:
    """Measured resolution of every drift item in TRANSITION_AUDIT.md section 2."""

    def tally(rows: list[Result]) -> str:
        counts = Counter(r.classification for r in rows)
        return ", ".join(f"{counts[c]} {c}" for c in CLASSES if counts[c]) or "none"

    p0 = _span(results, "RL-001", "RL-006")
    engine = _span(results, "RL-040", "RL-061")
    lines = [
        "## Reconciliation with the transition audit",
        "",
        "Each row of `PLAN/V2/TRANSITION_AUDIT.md` section 2 (planning-document drift), checked against the",
        "repository by this script.",
        "",
        "| Document | Claim | Measured | Resolution |",
        "|---|---|---|---|",
    ]
    for doc, claim, relative, task in DRIFT_NOTICE_DOCS:
        noted = _has_direction_notice(relative)
        verdict = "direction notice present" if noted else "**OPEN: no direction notice**"
        lines.append(f"| {doc} | {claim} | {verdict} | closed by `{task}`; nothing rewritten |")
    lines.append(
        f"| `PLAN/PROJECT_STATUS.md` section 1 | engine `P4`-`P7` not executed | `RL-040`-`RL-061`: {tally(engine)}"
        " | stale claim; code and tests exist |"
    )
    lines.append(
        f"| `PLAN/TASK_GRAPH.md` | Phase P0 `Complete` | `RL-001`-`RL-006`: {tally(p0)}"
        " | supported except rows listed under discrepancies; retained as the v1 record |"
    )
    workflow_claim = ROOT.parent / ".github" / "workflows" / "research-lab.yaml"
    workflow_real = ROOT.parent / ".github" / "workflows" / "custom-memory-engine.yaml"
    lines.append(
        "| Issue #12 title | `.github/workflows/research-lab.yaml` | "
        f"claimed file {'exists' if workflow_claim.exists() else 'missing'}; "
        f"`custom-memory-engine.yaml` {'exists' if workflow_real.exists() else 'missing'}"
        " | the evidence registry cites the real file (`RL-005`) |"
    )
    refactoring = (ROOT / "REFACTORING.md").read_text(encoding="utf-8")
    stale = "peer review on `#45`" in refactoring
    lines.append(
        "| `REFACTORING.md` section 6 | remaining work: peer review on `#45` | "
        f"sentence {'still present' if stale else 'absent'}; `RL-061` is "
        f"{next(r.classification for r in results if r.task == 'RL-061')} | "
        "historical sentence kept (additive-only policy); no action |"
    )
    return lines


def _git_sha() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=False
    )
    return result.stdout.strip() or "unknown"


def _cell(result: Result) -> str:
    if result.classification == "not-started":
        return "UNVERIFIED (nothing exists)"
    files = ", ".join(f"`{f}`" for f in result.files[:3])
    more = f" (+{len(result.files) - 3} more)" if len(result.files) > 3 else ""
    if result.tests:
        tests = ", ".join(f"`{t}`" for t in result.tests[:2])
        more_t = f" (+{len(result.tests) - 2})" if len(result.tests) > 2 else ""
        return f"{files}{more}; tests: {tests}{more_t}"
    return f"{files}{more}; tests: UNVERIFIED (no executable test)"


def render(results: list[Result], ran_tests: bool) -> str:
    """Render the generated audit document."""
    counts = Counter(r.classification for r in results)
    lines = [
        "# Status Audit (generated)",
        "",
        "> **Generated by `scripts/audit_status.py` from `PLAN/TASK_GRAPH.md` and `PLAN/V2/status_evidence.json`.**",
        "> Do not edit by hand; re-run the script. Task `E-001`.",
        "",
        f"- Source commit: `{_git_sha()}`",
        f"- Tests executed for this audit: {'yes' if ran_tests else 'no (registry check only)'}",
        "- A task is `code-verified` only if its named files exist **and** at least one named test passed.",
        "  Tests that need the disposable database are skipped without one, which downgrades those",
        "  tasks to `claimed-unverified` rather than passing them silently.",
        "",
        "## Summary",
        "",
        "| Classification | Tasks |",
        "|---|---:|",
        *[f"| `{c}` | {counts.get(c, 0)} |" for c in CLASSES],
        f"| **Total** | **{len(results)}** |",
        "",
        "## Discrepancies between claimed status and evidence",
        "",
    ]
    found = discrepancies(results)
    lines += [f"- {d}" for d in found] or ["None."]
    lines += ["", *reconciliation(results)]
    lines += [
        "",
        "## All tasks",
        "",
        "| Task | Claimed (TASK_GRAPH) | Audit | Evidence (file; test) | Notes |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        notes = "; ".join([*r.reasons, r.note] if r.note else r.reasons)
        lines.append(f"| `{r.task}` | {r.claim.strip('` ')} | `{r.classification}` | {_cell(r)} | {notes} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify registry completeness only; run no tests")
    parser.add_argument("--junit", type=Path, help="reuse an existing pytest junit XML instead of running tests")
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    claims = parse_task_graph(TASK_GRAPH.read_text(encoding="utf-8"))
    registry = load_registry(REGISTRY)
    problems = check_registry(claims, registry)
    for problem in problems:
        print(problem)
    if problems:
        print(f"audit_status: {len(problems)} problem(s); every task must be classified")
        return 1
    if args.check:
        print(f"audit_status: {len(claims)} tasks, all present in the evidence registry")
        return 0

    junit: dict[str, Outcome] = {}
    if args.junit:
        junit = read_junit(args.junit)
    else:
        tests = sorted({t for entry in registry.values() for t in entry.get("tests", [])})
        with tempfile.TemporaryDirectory() as tmp:
            junit_path = Path(tmp) / "junit.xml"
            run_pytest(tests, junit_path)
            if junit_path.exists():
                junit = read_junit(junit_path)
    results = audit(claims, registry, junit)
    args.out.write_text(render(results, bool(junit)), encoding="utf-8", newline="\n")
    counts = Counter(r.classification for r in results)
    print("audit_status:", ", ".join(f"{c}={counts.get(c, 0)}" for c in CLASSES), f"-> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
